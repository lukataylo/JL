const DOTS: Record<string, [number, number][]> = Object.fromEntries(
  Object.entries(BITMAPS).map(([k, rows]) => [k, rows.flatMap((r, y) => [...r].flatMap((ch, x) => (ch === "#" ? [[x, y] as [number, number]] : [])))]),
);

export type IconName = keyof typeof BITMAPS;

/** `strokeWidth` is accepted for API compatibility; it nudges dot weight slightly. */
export function Icon({ name, size = 20, strokeWidth = 1.8, ...rest }: { name: IconName | string; size?: number; strokeWidth?: number } & SVGProps<SVGSVGElement>) {
  const dots = DOTS[name] ?? DOTS.other;
  const r = Math.min(0.48, 0.42 + (strokeWidth - 1.8) * 0.04);
  return (
    <svg width={size} height={size} viewBox="-0.5 -0.5 10 10" fill="currentColor" aria-hidden="true" focusable="false" {...rest}>
      {dots.map(([x, y]) => <circle key={`${x}-${y}`} cx={x + 0.5} cy={y + 0.5} r={r} />)}
    </svg>
  );
}

